import assert from 'node:assert/strict';
const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value), removeItem: (key: string) => storage.delete(key) } });
Object.defineProperty(globalThis, 'window', { configurable: true, value: globalThis });
const { usePlanningStore, documentKey } = await import('./planning-store');
const originalFetch = globalThis.fetch;
const json = (body: unknown) => new Response(JSON.stringify(body), { headers: { 'Content-Type': 'application/json' } });
const plan = { id: 'p', workspaceId: 'one', title: 'First plan', status: 'draft' as const, createdAt: '2026-11-14', updatedAt: '2026-11-14', pinned: false, archivedAt: null };
try {
  const state = usePlanningStore.getState();
  state.toggleGroup('one', 'manual'); state.toggleGroup('one', 'orchestrator');
  assert.equal(usePlanningStore.getState().groups['one:manual'], true);
  assert.equal(usePlanningStore.getState().groups['one:planning'], undefined);
  assert.equal(usePlanningStore.getState().groups['two:manual'], undefined);
  state.select('one', 'p'); state.select('two', 'q');
  const handoff = state.prepareHandoff('one:p:manual');
  const otherHandoff = state.prepareHandoff('two:q:manual');
  assert.equal(state.prepareHandoff('one:p:manual'), handoff, 'ambiguous retries retain their request identity across other plans');
  state.acknowledgeHandoff('one:p:manual', 'late-unrelated-request');
  assert.equal(state.prepareHandoff('one:p:manual'), handoff);
  state.acknowledgeHandoff('one:p:manual', handoff);
  assert.notEqual(state.prepareHandoff('one:p:manual'), handoff, 'an explicitly started new run after success gets a fresh identity');
  assert.equal(state.prepareHandoff('two:q:manual'), otherHandoff);
  state.setDraft(documentKey('one', 'p', 'plan.md'), { content: 'new draft', baseContent: 'base', baseRevision: 'revision' });
  state.clearDraft(documentKey('one', 'p', 'plan.md'), 'older draft');
  assert.equal(usePlanningStore.getState().drafts[documentKey('one', 'p', 'plan.md')].content, 'new draft', 'a late save cannot erase newer typing');
  let release!: (value: Response) => void;
  globalThis.fetch = async () => new Promise(resolve => { release = resolve; });
  const loading = state.refresh('one');
  globalThis.fetch = async () => json(plan);
  await state.create('one', 'First plan');
  release(json([])); await loading;
  assert.equal(usePlanningStore.getState().plans.one.length, 1, 'stale hydration cannot erase a created plan');
  globalThis.fetch = async () => { throw new Error('Service unavailable'); };
  await state.refresh('one');
  assert.equal(usePlanningStore.getState().plans.one[0].id, 'p', 'temporary gateway failure preserves last known navigation');
  assert.equal(usePlanningStore.getState().activeByWorkspace.two, 'q');
  await usePlanningStore.persist.rehydrate();
  assert.equal(usePlanningStore.getState().groups['one:manual'], true, 'collapse preferences survive rehydration');
  assert.equal(usePlanningStore.getState().drafts[documentKey('one', 'p', 'plan.md')].content, 'new draft', 'base revision and draft survive rehydration');
  console.log('Planning navigation, stale hydration and draft retention tests passed.');
} finally { globalThis.fetch = originalFetch; }
